    /// **La signature** (Patrick, 04/10/2026 : « sur chaque document généré, on peut ajouter une phrase du type “document
    /// généré par fornews.ai” ») : « Document généré par fornews.ai le 4 octobre 2026. », dans la langue du document.
    public static func signature(_ langue: String, date: Date = Date()) -> String {
        let code = String(langue.prefix(2)).lowercased()
        let f = DateFormatter()
        f.locale = Locale(identifier: code)
        f.setLocalizedDateFormatFromTemplate("d MMMM yyyy")
        let jour = f.string(from: date)
        switch code {
        case "en": return "Document generated by fornews.ai on \(jour)."
        case "de": return "Dokument erstellt von fornews.ai am \(jour)."
        case "es": return "Documento generado por fornews.ai el \(jour)."
        case "it": return "Documento generato da fornews.ai il \(jour)."
        case "ja": return "fornews.ai が\(jour)に作成した文書。"
        case "ko": return "fornews.ai가 \(jour)에 생성한 문서입니다."
        case "zh": return "本文档由 fornews.ai 于\(jour)生成。"
        case "pt": return "Documento gerado por fornews.ai em \(jour)."
        case "nl": return "Document gegenereerd door fornews.ai op \(jour)."
        case "ru": return "Документ создан fornews.ai \(jour)."
        case "uk": return "Документ створено fornews.ai \(jour)."
        case "tr": return "Bu belge fornews.ai tarafından \(jour) tarihinde oluşturuldu."
        case "vi": return "Tài liệu do fornews.ai tạo ngày \(jour)."
        case "hi": return "यह दस्तावेज़ fornews.ai ने \(jour) को तैयार किया।"
        case "fr": return "Document généré par fornews.ai le \(jour)."
        default: return "Document generated by fornews.ai on \(jour)."
        }
    }

    /// Le document, terminé par la signature puis l'avertissement — une seule fois, même si l'on repasse dessus.
    public static func ajouter(_ markdown: String, langue: String, date: Date = Date()) -> String {
        let phrase = texte(langue)
        guard !markdown.contains(phrase) else { return markdown }
        let corps = markdown.trimmingCharacters(in: .whitespacesAndNewlines)
        // ⛔ Pas de `---` : seul sur sa ligne, il fait basculer md Viewer en DIAPORAMA (règle du 28/07, `RapportHistoireTests`).
        // Un filet en HTML à la place — md Viewer le dessine, le lecteur de l'app l'ignore.
        return corps + "\n\n" + filet + "\n\n*\(signature(langue, date: date))*  \n*\(phrase)*\n"
    }

    /// Le filet qui sépare le document de sa signature.
    public static let filet = "<div class=\"fornews-filet\" style=\"border-top:1px solid rgba(127,127,127,0.35);margin:28px 0 10px;\"></div>"

    /// Pour un texte SANS Markdown (le résumé d'un article partagé dans un message) : signature et avertissement en clair.
    public static func ajouterTexte(_ texte: String, langue: String, date: Date = Date()) -> String {
        let phrase = Self.texte(langue)
        guard !texte.contains(phrase) else { return texte }
        return texte.trimmingCharacters(in: .whitespacesAndNewlines) + "\n\n" + signature(langue, date: date) + "\n" + phrase
    }
}
