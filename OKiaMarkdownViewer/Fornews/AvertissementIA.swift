import Foundation

/// **La phrase d'avertissement sur les erreurs de l'IA, à la fin de chaque document généré** (Patrick, 04/10/2026 : « à la
/// fin de chaque document généré, tu ajoutes la phrase d'avertissement concernant les erreurs de l'IA, dans la langue de
/// l'utilisateur »).
///
/// Le texte est celui de la base de support d'ok-ia.ch (« Les limites de l'IA », `OK-ia/public/data/fornews-kb.md`), dans
/// les cinq langues de l'app. Rapport de veille, présentation, revue de presse, dossiers, briefing, éditorial partagé,
/// fiche d'article : tous finissent par lui, précédé de la signature (04/10/2026).
public enum AvertissementIA {

    public static func texte(_ langue: String) -> String {
        switch String(langue.prefix(2)).lowercased() {
        case "en":
            "Content generated by artificial intelligence is provided for information only and may contain errors or omissions; it must be checked and validated by the user before any use or decision. The original articles remain the reference."
        case "de":
            "Von künstlicher Intelligenz erzeugte Inhalte dienen nur der Information und können Fehler oder Auslassungen enthalten; sie müssen vor jeder Verwendung oder Entscheidung vom Benutzer geprüft und bestätigt werden. Maßgeblich bleiben die Originalartikel."
        case "es":
            "Los contenidos generados por inteligencia artificial se ofrecen a título indicativo y pueden contener errores u omisiones; el usuario debe verificarlos y validarlos antes de cualquier uso o toma de decisiones. Los artículos originales siguen siendo la referencia."
        case "it":
            "I contenuti generati dall'intelligenza artificiale sono forniti a titolo indicativo e possono contenere errori o omissioni; devono essere verificati e convalidati dall'utente prima di qualsiasi utilizzo o decisione. Gli articoli originali restano il riferimento."
        default:
            "Les contenus générés par l'intelligence artificielle sont fournis à titre indicatif et peuvent comporter des erreurs ou omissions ; ils doivent être vérifiés et validés par l'utilisateur avant toute utilisation ou prise de décision. Les articles d'origine restent la référence."
        }
    }

    /// **La signature** (Patrick, 04/10/2026 : « sur chaque document généré, on peut ajouter une phrase du type “document
    /// généré par fornews.ai” ») : « Document généré par fornews.ai le 4 octobre 2026. », dans la langue du document.
    public static func signature(_ langue: String, date: Date = Date()) -> String {
        let code = String(langue.prefix(2)).lowercased()
        let f = DateFormatter()
        f.locale = Locale(identifier: code)
        f.setLocalizedDateFormatFromTemplate("d MMMM yyyy")
        let jour = f.string(from: date)
        switch code {
        case "en": return "Document generated by fornews.ai on \(jour)."
        case "de": return "Dokument erstellt von fornews.ai am \(jour)."
        case "es": return "Documento generado por fornews.ai el \(jour)."
        case "it": return "Documento generato da fornews.ai il \(jour)."
        default: return "Document généré par fornews.ai le \(jour)."
        }
    }

    /// Le document, terminé par la signature puis l'avertissement — une seule fois, même si l'on repasse dessus.
    public static func ajouter(_ markdown: String, langue: String, date: Date = Date()) -> String {
        let phrase = texte(langue)
        guard !markdown.contains(phrase) else { return markdown }
        let corps = markdown.trimmingCharacters(in: .whitespacesAndNewlines)
        // ⛔ Pas de `---` : seul sur sa ligne, il fait basculer md Viewer en DIAPORAMA (règle du 28/07, `RapportHistoireTests`).
        // Un filet en HTML à la place — md Viewer le dessine, le lecteur de l'app l'ignore.
        return corps + "\n\n" + filet + "\n\n*\(signature(langue, date: date))*  \n*\(phrase)*\n"
    }

    /// Le filet qui sépare le document de sa signature.
    public static let filet = "<div class=\"fornews-filet\" style=\"border-top:1px solid rgba(127,127,127,0.35);margin:28px 0 10px;\"></div>"

    /// Pour un texte SANS Markdown (le résumé d'un article partagé dans un message) : signature et avertissement en clair.
    public static func ajouterTexte(_ texte: String, langue: String, date: Date = Date()) -> String {
        let phrase = Self.texte(langue)
        guard !texte.contains(phrase) else { return texte }
        return texte.trimmingCharacters(in: .whitespacesAndNewlines) + "\n\n" + signature(langue, date: date) + "\n" + phrase
    }
}
